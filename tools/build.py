#!/usr/bin/env python3
"""Build and check the EduSphere site.

    python3 tools/build.py            # regenerate the module grid, then verify
    python3 tools/build.py --check    # verify only, exit 1 on any problem

The module cards in index.html are generated from data/modules.json, between the
markers:

    <!-- modules:start -->
    <!-- modules:end -->

Everything else in index.html is hand-authored. Requires Python 3.9+, no packages.
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "index.html"
DATA = ROOT / "data" / "modules.json"
CATEGORIES = {"core", "operations", "platform"}
START = "<!-- modules:start"
END = "<!-- modules:end -->"


def load_modules() -> list[dict]:
    payload = json.loads(DATA.read_text(encoding="utf-8"))
    modules = payload.get("modules", [])
    if not modules:
        raise SystemExit("data/modules.json has no modules")

    seen: set[str] = set()
    for item in modules:
        for key in ("id", "category", "icon", "title", "description"):
            if not item.get(key):
                raise SystemExit(f"module {item!r} is missing '{key}'")
        if item["category"] not in CATEGORIES:
            raise SystemExit(f"{item['id']}: unknown category '{item['category']}'")
        if item["id"] in seen:
            raise SystemExit(f"duplicate module id: {item['id']}")
        seen.add(item["id"])
    return modules


def render(modules: list[dict]) -> str:
    lines = [f"        {START} — generated by tools/build.py from data/modules.json -->"]
    for item in modules:
        lines.append(
            '        <div class="card reveal" data-cat="{cat}">'
            '<div class="ico">{icon}</div>'
            "<h3>{title}</h3><p>{desc}</p></div>".format(
                cat=item["category"],
                icon=html.escape(item["icon"]),
                title=html.escape(item["title"], quote=False),
                desc=html.escape(item["description"], quote=False),
            )
        )
    lines.append(f"        {END}")
    return "\n".join(lines)


def rebuild() -> int:
    modules = load_modules()
    text = INDEX.read_text(encoding="utf-8")
    start = text.find(START)
    end = text.find(END)
    if start == -1 or end == -1 or end < start:
        raise SystemExit("module markers not found in index.html")

    head = text[:start]
    tail = text[end + len(END):]
    INDEX.write_text(head + render(modules) + tail, encoding="utf-8")
    return len(modules)


def check() -> list[str]:
    problems: list[str] = []
    text = INDEX.read_text(encoding="utf-8")

    for asset in re.findall(r'(?:href|src)="(assets/[^"]+)"', text):
        if not (ROOT / asset).exists():
            problems.append(f"missing asset: {asset}")

    modules = load_modules()
    if text.count('class="card reveal" data-cat=') != len(modules):
        problems.append("index.html module cards are out of sync with data/modules.json")

    if "<style>" in text:
        problems.append("index.html still carries an inline <style> block")
    if re.search(r"<script>(?!\s)</script>", text):
        problems.append("index.html still carries an inline <script> block")

    for tag in ("<html", "</html>", "<head>", "</head>", "<body>", "</body>"):
        if tag not in text:
            problems.append(f"index.html is missing {tag}")

    for required in ("assets/css/styles.css", "assets/js/app.js", "assets/js/search.js"):
        if required not in text:
            problems.append(f"index.html does not reference {required}")

    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the EduSphere static site")
    parser.add_argument("--check", action="store_true", help="verify without rewriting")
    args = parser.parse_args()

    count = 0 if args.check else rebuild()
    problems = check()

    if problems:
        for problem in problems:
            print(f"  ✗ {problem}")
        return 1

    if args.check:
        print(f"  ✓ index.html is in sync ({len(load_modules())} modules)")
    else:
        print(f"  ✓ rendered {count} module cards into index.html")
        print("  ✓ all assets present")
    return 0


if __name__ == "__main__":
    sys.exit(main())
